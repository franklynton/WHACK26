-- Trade offers between two gods in the same galaxy: "I give 50 metal for 40 of your food".
-- The offered goods leave the sender's stockpile when the offer is made (held here), so they
-- can't be spent twice. The other god has 30 seconds to accept or decline:
--   accepted  -> the receiver pays what was asked and gets the held goods; the sender gets paid
--   declined, expired (30s), cancelled by the sender, or either god left the galaxy -> held goods go back
-- Everything settles here; each game picks up the new totals on its next sync (migration 008).
--
-- Also fixes goods going missing when gods leave: open market orders of a god who has left
-- the galaxy are cancelled and refunded, before an empty galaxy (and its order book) is deleted.
-- Safe to run more than once.

create table if not exists public.trade_offers (
  id bigint generated by default as identity primary key,
  galaxy text not null,
  from_world_id text not null references public.planets(world_id) on delete cascade,
  to_world_id text not null references public.planets(world_id) on delete cascade,
  from_name text not null,
  to_name text not null,
  give_resource text not null check (give_resource in ('food', 'wood', 'stone', 'metal', 'gold', 'herbs')),
  give_amount integer not null check (give_amount between 1 and 100000),
  want_resource text not null check (want_resource in ('food', 'wood', 'stone', 'metal', 'gold', 'herbs')),
  want_amount integer not null check (want_amount between 1 and 100000),
  status text not null default 'pending' check (status in ('pending', 'accepted', 'declined', 'expired', 'cancelled')),
  reason text, -- why a non-accepted offer ended, in words the game can show
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default now() + interval '30 seconds',
  resolved_at timestamptz
);
create index if not exists trade_offers_to on public.trade_offers (to_world_id, status);
create index if not exists trade_offers_from on public.trade_offers (from_world_id, created_at desc);
alter table public.trade_offers enable row level security; -- only the functions below and the server touch it
grant all privileges on table public.trade_offers to service_role;

create or replace function public.trade_offer_seconds() returns integer language sql immutable as $$ select 30 $$;

-- Adds n of resource r to a planet's stockpile (n may be negative; never below zero).
create or replace function public.add_resource(p_world_id text, r text, n bigint)
returns void language sql security definer set search_path = public as $$
  update planets
    set resources = jsonb_set(resources, array[r], to_jsonb(greatest(0, coalesce((resources->>r)::numeric, 0)::bigint + n)), true),
        updated_at = updated_at -- a refund isn't a sign of life; leave the online clock alone
    where world_id = p_world_id;
$$;

-- Ends a pending offer without a trade and gives the held goods back to the sender.
create or replace function public.refund_trade_offer(p_id bigint, p_status text, p_reason text)
returns void language plpgsql security definer set search_path = public as $$
declare o trade_offers%rowtype;
begin
  select * into o from trade_offers where id = p_id and status = 'pending' for update;
  if not found then return; end if;
  perform add_resource(o.from_world_id, o.give_resource, o.give_amount);
  update trade_offers set status = p_status, reason = p_reason, resolved_at = now() where id = p_id;
end;
$$;

-- Drops gods who stopped syncing, settles offers and market orders they can no longer take part in,
-- then deletes galaxies nobody is in. (Replaces 003's version.)
create or replace function public.galaxy_tidy()
returns void language plpgsql security definer set search_path = public as $$
declare
  o record;
begin
  update planets set galaxy = null where galaxy is not null and updated_at < now() - interval '30 seconds';

  for o in select id from trade_offers where status = 'pending' and expires_at <= now() loop
    perform refund_trade_offer(o.id, 'expired', 'No answer in time');
  end loop;
  for o in
    select t.id from trade_offers t
    join planets f on f.world_id = t.from_world_id
    join planets r on r.world_id = t.to_world_id
    where t.status = 'pending' and (f.galaxy is distinct from t.galaxy or r.galaxy is distinct from t.galaxy)
  loop
    perform refund_trade_offer(o.id, 'cancelled', 'A god left the galaxy');
  end loop;

  -- Market orders of gods who are no longer in that galaxy: refund what they held (as cancel_market_order does).
  if to_regclass('public.market_orders') is not null then
    for o in
      select m.id, m.world_id, m.side, m.resource, m.escrow_quantity, m.escrow_credits
      from market_orders m join planets p on p.world_id = m.world_id
      where m.status in ('open', 'partial') and p.galaxy is distinct from m.galaxy
      for update of m
    loop
      if o.side = 'buy' then
        update planets set credits = credits + o.escrow_credits where world_id = o.world_id;
      else
        perform add_resource(o.world_id, o.resource, o.escrow_quantity);
      end if;
      update market_orders set status = 'cancelled', remaining = 0, escrow_quantity = 0, escrow_credits = 0 where id = o.id;
    end loop;
  end if;

  delete from galaxies g where not exists (select 1 from planets p where p.galaxy = g.code);
end;
$$;

-- Leaving and moving galaxies now go through galaxy_tidy, so offers and orders are settled
-- before an emptied galaxy is deleted (deleting it would take its order book with it).
create or replace function public.leave_galaxy(p_world_id text, p_owner_token text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  me planets%rowtype;
begin
  select * into me from planets where world_id = p_world_id for update;
  if not found then return jsonb_build_object('ok', true); end if;
  if me.owner_token <> p_owner_token then raise exception 'Not your planet'; end if;
  update planets set galaxy = null where world_id = p_world_id;
  perform galaxy_tidy();
  return jsonb_build_object('ok', true, 'left', me.galaxy);
end;
$$;

-- 007's version, with the old galaxy left to galaxy_tidy instead of being deleted directly.
create or replace function public.join_galaxy(p_world_id text, p_owner_token text, p_code text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  c text := upper(trim(coalesce(p_code, '')));
  me planets%rowtype;
  made text;
  members integer;
begin
  if c !~ '^[A-Z0-9]{3,12}$' then
    return jsonb_build_object('ok', false, 'reason', 'invalid');
  end if;
  select * into me from planets where world_id = p_world_id for update;
  if not found then return jsonb_build_object('ok', false, 'reason', 'no_planet'); end if;
  if me.owner_token <> p_owner_token then raise exception 'Not your planet'; end if;

  perform galaxy_tidy();
  insert into galaxies (code) values (c) on conflict (code) do nothing returning code into made;
  if to_regprocedure('public.initialize_market_prices(text)') is not null then
    perform public.initialize_market_prices(c);
  end if;
  perform 1 from galaxies where code = c for update;

  if me.galaxy = c then
    select count(*) into members from planets where galaxy = c;
    return jsonb_build_object('ok', true, 'created', false, 'galaxy', c, 'members', members);
  end if;

  select count(*) into members from planets where galaxy = c;
  if members >= galaxy_max() then
    return jsonb_build_object('ok', false, 'reason', 'full', 'galaxy', c, 'members', members);
  end if;

  update planets set galaxy = c, updated_at = now() where world_id = p_world_id;
  perform galaxy_tidy();
  return jsonb_build_object('ok', true, 'created', made is not null, 'galaxy', c, 'members', members + 1);
end;
$$;

-- Makes an offer. Returns {ok, id, seconds} or {ok: false, reason}.
create or replace function public.make_trade_offer(
  p_world_id text, p_owner_token text, p_target_world_id text,
  p_give_resource text, p_give_amount integer, p_want_resource text, p_want_amount integer
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  me planets%rowtype;
  them planets%rowtype;
  have bigint;
  pending integer;
  new_id bigint;
begin
  if p_give_resource not in ('food', 'wood', 'stone', 'metal', 'gold', 'herbs')
     or p_want_resource not in ('food', 'wood', 'stone', 'metal', 'gold', 'herbs')
     or p_give_amount not between 1 and 100000 or p_want_amount not between 1 and 100000 then
    return jsonb_build_object('ok', false, 'reason', 'invalid');
  end if;
  if p_give_resource = p_want_resource then return jsonb_build_object('ok', false, 'reason', 'same_resource'); end if;
  if p_world_id = p_target_world_id then return jsonb_build_object('ok', false, 'reason', 'self'); end if;

  perform galaxy_tidy();
  select * into me from planets where world_id = p_world_id for update;
  if not found then return jsonb_build_object('ok', false, 'reason', 'no_planet'); end if;
  if me.owner_token <> p_owner_token then raise exception 'Not your planet'; end if;
  select * into them from planets where world_id = p_target_world_id;
  if me.galaxy is null or not found or them.galaxy is distinct from me.galaxy then
    return jsonb_build_object('ok', false, 'reason', 'not_in_galaxy');
  end if;

  select count(*) into pending from trade_offers where from_world_id = p_world_id and status = 'pending';
  if pending >= 3 then return jsonb_build_object('ok', false, 'reason', 'too_many'); end if;

  have := greatest(0, coalesce((me.resources->>p_give_resource)::numeric, 0)::bigint);
  if have < p_give_amount then
    return jsonb_build_object('ok', false, 'reason', 'not_enough', 'have', have);
  end if;

  perform add_resource(p_world_id, p_give_resource, -p_give_amount); -- held until the offer ends
  insert into trade_offers (galaxy, from_world_id, to_world_id, from_name, to_name, give_resource, give_amount, want_resource, want_amount, expires_at)
    values (me.galaxy, p_world_id, p_target_world_id, me.planet_name, them.planet_name, p_give_resource, p_give_amount, p_want_resource, p_want_amount,
            now() + make_interval(secs => trade_offer_seconds()))
    returning id into new_id;
  return jsonb_build_object('ok', true, 'id', new_id, 'seconds', trade_offer_seconds());
end;
$$;

-- The receiver accepts or declines. Returns {ok, status} or {ok: false, reason: 'gone' | 'not_enough'}.
create or replace function public.answer_trade_offer(p_world_id text, p_owner_token text, p_offer_id bigint, p_accept boolean)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  o trade_offers%rowtype;
  me planets%rowtype;
  have bigint;
begin
  perform galaxy_tidy(); -- settles an offer that has just run out of time
  select * into me from planets where world_id = p_world_id for update;
  if not found then return jsonb_build_object('ok', false, 'reason', 'gone'); end if;
  if me.owner_token <> p_owner_token then raise exception 'Not your planet'; end if;
  select * into o from trade_offers where id = p_offer_id and to_world_id = p_world_id for update;
  if not found or o.status <> 'pending' then
    return jsonb_build_object('ok', false, 'reason', 'gone', 'status', coalesce(o.status, 'missing'));
  end if;

  if not p_accept then
    perform refund_trade_offer(o.id, 'declined', 'Declined');
    return jsonb_build_object('ok', true, 'status', 'declined');
  end if;

  have := greatest(0, coalesce((me.resources->>o.want_resource)::numeric, 0)::bigint);
  if have < o.want_amount then
    return jsonb_build_object('ok', false, 'reason', 'not_enough', 'have', have);
  end if;

  perform add_resource(o.to_world_id, o.want_resource, -o.want_amount);
  perform add_resource(o.to_world_id, o.give_resource, o.give_amount);
  perform add_resource(o.from_world_id, o.want_resource, o.want_amount);
  update trade_offers set status = 'accepted', resolved_at = now() where id = o.id;
  return jsonb_build_object('ok', true, 'status', 'accepted');
end;
$$;

-- The sender takes an offer back before it's answered.
create or replace function public.cancel_trade_offer(p_world_id text, p_owner_token text, p_offer_id bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  owner text;
begin
  select owner_token into owner from planets where world_id = p_world_id;
  if owner is distinct from p_owner_token then raise exception 'Not your planet'; end if;
  if not exists (select 1 from trade_offers where id = p_offer_id and from_world_id = p_world_id) then
    return jsonb_build_object('ok', false, 'reason', 'gone');
  end if;
  perform refund_trade_offer(p_offer_id, 'cancelled', 'Taken back');
  return jsonb_build_object('ok', true, 'status', (select status from trade_offers where id = p_offer_id));
end;
$$;

-- Only the server (service role, through /api/galaxy) may call these.
do $$
declare f text;
begin
  foreach f in array array[
    'add_resource(text, text, bigint)', 'refund_trade_offer(bigint, text, text)', 'galaxy_tidy()',
    'leave_galaxy(text, text)', 'join_galaxy(text, text, text)',
    'make_trade_offer(text, text, text, text, integer, text, integer)',
    'answer_trade_offer(text, text, bigint, boolean)', 'cancel_trade_offer(text, text, bigint)'
  ] loop
    execute format('revoke all on function public.%s from public, anon, authenticated', f);
    execute format('grant execute on function public.%s to service_role', f);
  end loop;
end;
$$;
