-- Invasions between planets take 30 seconds and both gods see them coming.
--   launch_invasion  -> the attacker commits part of its army (the game takes those people off its globe)
--                       and a fleet sets off; it lands 30 seconds later
--   answer_invasion  -> the defender may fight (the default), pay tribute (15% of gold and food, no battle)
--                       or raise shields (+50% defence; the game spends the god's devotion)
--   settle_invasions -> fleets that have arrived fight. The result is a normal 'invasion' row in
--                       planet_actions with the loot and losses, which each game applies to its own sim.
-- Strength: each game sends its own attack (fleet x race) and defence (army, warships, race, era);
-- the planet-type matchup (weakTo in src/sim/planet.ts) and the dice are added here.
-- Loot moves between the two resources rows, so it reaches each game with its next sync (migration 008).
-- The old galaxy_invade stays, and the game falls back to it until this migration is run.
-- Safe to run more than once.

alter table public.planets add column if not exists defence real not null default 0;

create table if not exists public.invasion_fleets (
  id bigint generated by default as identity primary key,
  galaxy text not null,
  from_world_id text not null references public.planets(world_id) on delete cascade,
  to_world_id text not null references public.planets(world_id) on delete cascade,
  from_name text not null,
  to_name text not null,
  fleet integer not null check (fleet between 1 and 100000),
  attack real not null,
  answer text not null default 'fight' check (answer in ('fight', 'tribute', 'shields')),
  status text not null default 'flying' check (status in ('flying', 'done')),
  launched_at timestamptz not null default now(),
  arrives_at timestamptz not null default now() + interval '30 seconds'
);
create index if not exists invasion_fleets_flying on public.invasion_fleets (status, arrives_at);
alter table public.invasion_fleets enable row level security; -- only the functions below and the server touch it
grant all privileges on table public.invasion_fleets to service_role;

-- 1.5 when the defender's planet type is weak to the attacker's, 0.67 the other way round (invasionBonus in planet.ts).
create or replace function public.invasion_bonus(p_attacker text, p_defender text)
returns real language sql immutable as $$
  select case
    when (p_defender, p_attacker) in (('Verdant','Ironworld'), ('Timberworld','Verdant'), ('Ironworld','Gilded'), ('Gilded','Archipelago'), ('Archipelago','Timberworld')) then 1.5
    when (p_attacker, p_defender) in (('Verdant','Ironworld'), ('Timberworld','Verdant'), ('Ironworld','Gilded'), ('Gilded','Archipelago'), ('Archipelago','Timberworld')) then 0.67
    else 1 end::real
$$;

create or replace function public.launch_invasion(
  p_world_id text, p_owner_token text, p_target_world_id text, p_fleet integer, p_attack real
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  me planets%rowtype;
  them planets%rowtype;
  f invasion_fleets%rowtype;
begin
  select * into me from planets where world_id = p_world_id for update;
  if not found then return jsonb_build_object('ok', false, 'reason', 'no_planet'); end if;
  if me.owner_token <> p_owner_token then raise exception 'Not your planet'; end if;
  if p_world_id = p_target_world_id then return jsonb_build_object('ok', false, 'reason', 'self'); end if;
  if not same_galaxy(p_world_id, p_target_world_id) then return jsonb_build_object('ok', false, 'reason', 'not_in_galaxy'); end if;
  if coalesce(p_fleet, 0) < 1 then return jsonb_build_object('ok', false, 'reason', 'no_army'); end if;
  if exists (select 1 from invasion_fleets where from_world_id = p_world_id and status = 'flying') then
    return jsonb_build_object('ok', false, 'reason', 'flying');
  end if;
  if me.invasion_cooldown_until is not null and me.invasion_cooldown_until > now() then
    return jsonb_build_object('ok', false, 'reason', 'cooldown', 'seconds', ceil(extract(epoch from me.invasion_cooldown_until - now())));
  end if;
  select * into them from planets where world_id = p_target_world_id;

  insert into invasion_fleets (galaxy, from_world_id, to_world_id, from_name, to_name, fleet, attack)
  values (me.galaxy, me.world_id, them.world_id, me.planet_name, them.planet_name,
          least(p_fleet, greatest(me.population, 1)),
          least(greatest(coalesce(p_attack, 0), 0), least(p_fleet, greatest(me.population, 1)) * 3)) -- can't claim more than 3 per soldier
  returning * into f;
  update planets set invasion_cooldown_until = now() + interval '2 minutes' where world_id = me.world_id;
  return jsonb_build_object('ok', true, 'id', f.id, 'fleet', f.fleet, 'seconds', 30);
end;
$$;

-- Loot taken from a planet: share of what it holds of resource r, capped. Moves it to the winner.
create or replace function public.take_resource(p_from text, p_to text, r text, p_share real, p_cap integer)
returns integer language plpgsql security definer set search_path = public as $$
declare n integer;
begin
  select least(p_cap, floor(greatest(coalesce((resources->>r)::numeric, 0), 0) * p_share))::integer into n from planets where world_id = p_from;
  n := coalesce(n, 0);
  if n > 0 then
    perform add_resource(p_from, r, -n);
    perform add_resource(p_to, r, n);
  end if;
  return n;
end;
$$;

create or replace function public.answer_invasion(p_world_id text, p_owner_token text, p_fleet_id bigint, p_answer text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  me planets%rowtype;
  f invasion_fleets%rowtype;
  gold integer;
  food integer;
begin
  select * into me from planets where world_id = p_world_id;
  if not found or me.owner_token <> p_owner_token then raise exception 'Not your planet'; end if;
  if p_answer not in ('fight', 'tribute', 'shields') then return jsonb_build_object('ok', false, 'reason', 'invalid'); end if;
  select * into f from invasion_fleets where id = p_fleet_id and to_world_id = p_world_id and status = 'flying' for update;
  if not found then return jsonb_build_object('ok', false, 'reason', 'gone'); end if;

  if p_answer <> 'tribute' then
    update invasion_fleets set answer = p_answer where id = f.id;
    return jsonb_build_object('ok', true, 'answer', p_answer);
  end if;

  -- Tribute: no battle. The fleet goes home whole with 15% of the defender's gold and food.
  gold := take_resource(f.to_world_id, f.from_world_id, 'gold', 0.15, 500);
  food := take_resource(f.to_world_id, f.from_world_id, 'food', 0.15, 500);
  update invasion_fleets set answer = 'tribute', status = 'done' where id = f.id;
  insert into planet_actions (source_world_id, target_world_id, action_type, payload, status, message)
  values (f.from_world_id, f.to_world_id, 'invasion',
    jsonb_build_object('fleet_id', f.id, 'result', 'tribute', 'won', true, 'fleet', f.fleet, 'attacker_lost', 0, 'defender_lost', 0,
                       'loot', jsonb_build_object('gold', gold, 'food', food)),
    'completed', f.to_name || ' paid ' || f.from_name || ' tribute: ' || gold || ' gold and ' || food || ' food');
  return jsonb_build_object('ok', true, 'answer', 'tribute', 'gold', gold, 'food', food);
end;
$$;

-- Fights every fleet that has arrived. Called by both games' polls, so it locks each fleet once.
create or replace function public.settle_invasions()
returns integer language plpgsql security definer set search_path = public as $$
declare
  f invasion_fleets%rowtype;
  a planets%rowtype;
  d planets%rowtype;
  att real;
  def real;
  won boolean;
  loot jsonb;
  a_lost integer;
  d_lost integer;
  settled integer := 0;
begin
  for f in select * from invasion_fleets where status = 'flying' and arrives_at <= now() order by id for update skip locked loop
    select * into a from planets where world_id = f.from_world_id;
    select * into d from planets where world_id = f.to_world_id;
    update invasion_fleets set status = 'done' where id = f.id;
    settled := settled + 1;

    if not same_galaxy(f.from_world_id, f.to_world_id) then
      -- Someone left the galaxy while the fleet was in flight: it turns round.
      insert into planet_actions (source_world_id, target_world_id, action_type, payload, status, message)
      values (f.from_world_id, f.to_world_id, 'invasion',
        jsonb_build_object('fleet_id', f.id, 'result', 'recalled', 'won', false, 'fleet', f.fleet, 'attacker_lost', 0, 'defender_lost', 0),
        'completed', f.from_name || '''s fleet found ' || f.to_name || ' gone and turned home');
      continue;
    end if;

    att := f.attack * invasion_bonus(a.planet_type, d.planet_type) * (0.8 + 0.4 * random());
    def := greatest(d.defence, d.military)::real * (case when f.answer = 'shields' then 1.5 else 1 end) * (0.8 + 0.4 * random());
    won := att > def;
    if won then
      loot := jsonb_build_object(
        'gold', take_resource(d.world_id, a.world_id, 'gold', 0.1, 200),
        'metal', take_resource(d.world_id, a.world_id, 'metal', 0.1, 200),
        'food', take_resource(d.world_id, a.world_id, 'food', 0.1, 200));
      a_lost := round(f.fleet * 0.2);
      d_lost := least(ceil(f.fleet / 3.0)::integer, greatest(d.population - 5, 0));
    else
      loot := '{}'::jsonb;
      a_lost := round(f.fleet * 0.6);
      d_lost := round(greatest(d.military, 0) * 0.1);
    end if;

    insert into planet_actions (source_world_id, target_world_id, action_type, payload, status, message)
    values (f.from_world_id, f.to_world_id, 'invasion',
      jsonb_build_object('fleet_id', f.id, 'result', case when won then 'won' else 'repelled' end, 'won', won,
                         'fleet', f.fleet, 'attacker_lost', a_lost, 'defender_lost', d_lost, 'loot', loot,
                         'shields', f.answer = 'shields', 'attack', round(att), 'defence', round(def)),
      'completed',
      case when won then f.from_name || ' invaded ' || f.to_name else f.to_name || ' repelled the fleet from ' || f.from_name end);
  end loop;
  return settled;
end;
$$;

do $$
declare fn text;
begin
  foreach fn in array array[
    'invasion_bonus(text, text)', 'launch_invasion(text, text, text, integer, real)', 'take_resource(text, text, text, real, integer)',
    'answer_invasion(text, text, bigint, text)', 'settle_invasions()'
  ] loop
    execute format('revoke all on function public.%s from public, anon, authenticated', fn);
    execute format('grant execute on function public.%s to service_role', fn);
  end loop;
end;
$$;
