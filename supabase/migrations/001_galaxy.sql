create or replace function public.sync_planet(
  p_world_id text,
  p_owner_token text,
  p_owner_name text,
  p_planet_name text,
  p_planet_type text,
  p_population integer,
  p_villages integer,
  p_output integer,
  p_military integer,
  p_resources jsonb,
  p_position_x real,
  p_position_y real
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  existing_token text;
begin
  select owner_token into existing_token from planets where world_id = p_world_id;
  if existing_token is not null and existing_token <> p_owner_token then
    raise exception 'World is owned by another player';
  end if;

  insert into planets (
    world_id, owner_token, owner_name, planet_name, planet_type, population, villages,
    output, military, resources, position_x, position_y
  ) values (
    p_world_id, p_owner_token, p_owner_name, p_planet_name, p_planet_type, greatest(p_population, 0),
    greatest(p_villages, 0), greatest(p_output, 0), greatest(p_military, 0), p_resources,
    least(greatest(p_position_x, 0), 1), least(greatest(p_position_y, 0), 1)
  )
  on conflict (world_id) do update set
    owner_name = excluded.owner_name,
    planet_name = excluded.planet_name,
    planet_type = excluded.planet_type,
    population = excluded.population,
    villages = excluded.villages,
    output = excluded.output,
    military = excluded.military,
    position_x = excluded.position_x,
    position_y = excluded.position_y,
    updated_at = now();

  return (select to_jsonb(p) from planets p where p.world_id = p_world_id);
end;
$$;

create or replace function public.trade_planet(
  p_source_world_id text,
  p_owner_token text,
  p_target_world_id text,
  p_resource text,
  p_amount integer
)
returns text language plpgsql security definer set search_path = public as $$
declare
  source planets%rowtype;
  target planets%rowtype;
  available integer;
  source_resources jsonb;
  target_resources jsonb;
  message text;
begin
  if p_resource not in ('food', 'wood', 'stone', 'metal', 'gold', 'herbs') then
    raise exception 'Unknown resource';
  end if;
  if p_amount < 1 or p_amount > 10000 then
    raise exception 'Amount must be between 1 and 10000';
  end if;

  select * into source from planets where world_id = p_source_world_id for update;
  if not found then raise exception 'Source planet not found'; end if;
  if source.owner_token <> p_owner_token then raise exception 'Not your planet'; end if;
  if source.world_id = p_target_world_id then raise exception 'Cannot trade with your own planet'; end if;

  select * into target from planets where world_id = p_target_world_id for update;
  if not found then raise exception 'Target planet not found'; end if;

  available := greatest(coalesce((source.resources->>p_resource)::integer, 0), 0);
  if available < p_amount then
    insert into planet_actions(source_world_id, target_world_id, action_type, payload, status, message)
    values (source.world_id, target.world_id, 'trade', jsonb_build_object('resource', p_resource, 'amount', p_amount), 'blocked', 'Trade blocked: not enough ' || p_resource);
    return 'Trade blocked: not enough ' || p_resource;
  end if;

  source_resources := source.resources;
  target_resources := target.resources;
  source_resources := jsonb_set(source_resources, array[p_resource], to_jsonb(available - p_amount));
  target_resources := jsonb_set(target_resources, array[p_resource], to_jsonb(greatest(coalesce((target_resources->>p_resource)::integer, 0), 0) + p_amount));

  update planets set resources = source_resources, updated_at = now() where world_id = source.world_id;
  update planets set resources = target_resources, updated_at = now() where world_id = target.world_id;

  message := 'Sent ' || p_amount || ' ' || p_resource || ' to ' || target.planet_name;
  insert into planet_actions(source_world_id, target_world_id, action_type, payload, status, message)
  values (source.world_id, target.world_id, 'trade', jsonb_build_object('resource', p_resource, 'amount', p_amount), 'completed', message);
  return message;
end;
$$;

create or replace function public.invade_planet(
  p_source_world_id text,
  p_owner_token text,
  p_target_world_id text
)
returns text language plpgsql security definer set search_path = public as $$
declare
  source planets%rowtype;
  target planets%rowtype;
  won boolean;
  attacker_score integer;
  defender_score integer;
  message text;
begin
  select * into source from planets where world_id = p_source_world_id for update;
  if not found then raise exception 'Source planet not found'; end if;
  if source.owner_token <> p_owner_token then raise exception 'Not your planet'; end if;
  if source.world_id = p_target_world_id then raise exception 'Cannot invade your own planet'; end if;
  if source.invasion_cooldown_until is not null and source.invasion_cooldown_until > now() then
    return 'Invasion blocked: military fleets are still returning';
  end if;

  select * into target from planets where world_id = p_target_world_id for update;
  if not found then raise exception 'Target planet not found'; end if;

  attacker_score := source.military + floor(random() * 31)::integer;
  defender_score := target.military + floor(random() * 21)::integer;
  won := attacker_score >= defender_score;

  if won then
    update planets set
      resources = jsonb_set(resources, '{gold}', to_jsonb(greatest(coalesce((resources->>'gold')::integer, 0), 0) + 20)),
      military = greatest(military - 10, 0),
      updated_at = now()
    where world_id = source.world_id;
    update planets set
      population = greatest(population - 20, 0),
      military = greatest(military - 15, 0),
      updated_at = now()
    where world_id = target.world_id;
    message := source.planet_name || ' conquered supplies from ' || target.planet_name;
  else
    update planets set military = greatest(military - 15, 0), updated_at = now() where world_id = source.world_id;
    update planets set military = greatest(military - 5, 0), updated_at = now() where world_id = target.world_id;
    message := source.planet_name || ' was repelled by ' || target.planet_name;
  end if;

  update planets set invasion_cooldown_until = now() + interval '10 minutes' where world_id = source.world_id;
  insert into planet_actions(source_world_id, target_world_id, action_type, payload, status, message)
  values (source.world_id, target.world_id, 'invasion', jsonb_build_object('won', won, 'attacker_score', attacker_score, 'defender_score', defender_score), 'completed', message);
  return message;
end;
$$;

grant execute on function public.sync_planet(text, text, text, text, text, integer, integer, integer, integer, jsonb, real, real) to service_role;
grant execute on function public.trade_planet(text, text, text, text, integer) to service_role;
grant execute on function public.invade_planet(text, text, text) to service_role;
