create extension if not exists pgcrypto;

create table if not exists public.planets (
  world_id text primary key default gen_random_uuid()::text,
  owner_token text not null,
  owner_name text not null,
  planet_name text not null,
  planet_type text not null default 'Unknown',
  population integer not null default 0,
  villages integer not null default 0,
  output integer not null default 0,
  military integer not null default 0,
  resources jsonb not null default '{"food":0,"wood":0,"stone":0,"metal":0,"gold":0,"herbs":0}'::jsonb,
  position_x real not null default 0.5,
  position_y real not null default 0.5,
  invasion_cooldown_until timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.planet_actions (
  id bigint generated by default as identity primary key,
  source_world_id text references public.planets(world_id),
  target_world_id text references public.planets(world_id),
  action_type text not null check (action_type in ('trade', 'invasion')),
  payload jsonb not null default '{}'::jsonb,
  status text not null check (status in ('completed', 'blocked')),
  message text not null,
  created_at timestamptz not null default now()
);

grant usage on schema public to anon, authenticated, service_role;
grant all privileges on table public.planets to service_role;
grant all privileges on table public.planet_actions to service_role;
grant all privileges on sequence public.planet_actions_id_seq to service_role;
grant select on table public.planets to anon, authenticated;
grant select on table public.planet_actions to anon, authenticated;

alter table public.planets enable row level security;
alter table public.planet_actions enable row level security;

drop policy if exists "Public planet snapshots" on public.planets;
create policy "Public planet snapshots" on public.planets
  for select using (true);
drop policy if exists "Public action history" on public.planet_actions;
create policy "Public action history" on public.planet_actions
  for select using (true);

