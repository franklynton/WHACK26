-- Per-galaxy limit order books. Money is represented as integer credits.
-- A buy escrows credits and a sell escrows goods when placed.

alter table public.planets
  add column if not exists credits bigint not null default 1000;

create table if not exists public.market_orders (
  id bigint generated by default as identity primary key,
  galaxy text not null references public.galaxies(code) on delete cascade,
  world_id text not null references public.planets(world_id) on delete cascade,
  side text not null check (side in ('buy', 'sell')),
  resource text not null check (resource in ('food', 'wood', 'stone', 'metal', 'gold', 'herbs')),
  price bigint not null check (price > 0),
  quantity integer not null check (quantity > 0),
  remaining integer not null check (remaining >= 0 and remaining <= quantity),
  escrow_quantity integer not null default 0 check (escrow_quantity >= 0),
  escrow_credits bigint not null default 0 check (escrow_credits >= 0),
  status text not null default 'open' check (status in ('open', 'partial', 'filled', 'cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.market_trades (
  id bigint generated by default as identity primary key,
  galaxy text not null references public.galaxies(code) on delete cascade,
  resource text not null check (resource in ('food', 'wood', 'stone', 'metal', 'gold', 'herbs')),
  price bigint not null check (price > 0),
  quantity integer not null check (quantity > 0),
  buyer_world_id text not null references public.planets(world_id) on delete cascade,
  seller_world_id text not null references public.planets(world_id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists market_orders_book
  on public.market_orders (galaxy, resource, side, price, created_at, id)
  where status in ('open', 'partial');
create index if not exists market_trades_galaxy on public.market_trades (galaxy, created_at desc);

alter table public.market_orders enable row level security;
alter table public.market_trades enable row level security;

grant all privileges on table public.market_orders to service_role;
grant all privileges on table public.market_trades to service_role;
grant usage, select on sequence public.market_orders_id_seq to service_role;
grant usage, select on sequence public.market_trades_id_seq to service_role;

create or replace function public.place_market_order(
  p_world_id text,
  p_owner_token text,
  p_side text,
  p_resource text,
  p_price bigint,
  p_quantity integer
) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  me planets%rowtype;
  incoming market_orders%rowtype;
  resting market_orders%rowtype;
  trade_price bigint;
  filled integer;
  reserve_qty integer;
  cost bigint;
  refunded bigint;
  buyer planets%rowtype;
  seller planets%rowtype;
begin
  if p_side not in ('buy', 'sell') then raise exception 'Side must be buy or sell'; end if;
  if p_resource not in ('food', 'wood', 'stone', 'metal', 'gold', 'herbs') then raise exception 'Unknown resource'; end if;
  if p_price < 1 then raise exception 'Price must be positive'; end if;
  if p_quantity < 1 or p_quantity > 100000 then raise exception 'Quantity must be between 1 and 100000'; end if;

  select * into me from planets where world_id = p_world_id for update;
  if not found then raise exception 'Planet not found'; end if;
  if me.owner_token <> p_owner_token then raise exception 'Not your planet'; end if;
  if me.galaxy is null then raise exception 'Join a galaxy first'; end if;

  if p_side = 'buy' then
    cost := p_price * p_quantity;
    if me.credits < cost then raise exception 'Not enough credits'; end if;
    update planets set credits = credits - cost, updated_at = now() where world_id = p_world_id;
    insert into market_orders(galaxy, world_id, side, resource, price, quantity, remaining, escrow_credits, status)
    values (me.galaxy, p_world_id, 'buy', p_resource, p_price, p_quantity, p_quantity, cost, 'open')
    returning * into incoming;
  else
    reserve_qty := greatest(coalesce((me.resources->>p_resource)::integer, 0), 0);
    if reserve_qty < p_quantity then raise exception 'Not enough %', p_resource; end if;
    update planets set resources = jsonb_set(resources, array[p_resource], to_jsonb(reserve_qty - p_quantity), true), updated_at = now()
    where world_id = p_world_id;
    insert into market_orders(galaxy, world_id, side, resource, price, quantity, remaining, escrow_quantity, status)
    values (me.galaxy, p_world_id, 'sell', p_resource, p_price, p_quantity, p_quantity, p_quantity, 'open')
    returning * into incoming;
  end if;

  loop
    if incoming.side = 'buy' then
      select * into resting from market_orders
      where galaxy = incoming.galaxy and resource = incoming.resource and side = 'sell'
        and status in ('open', 'partial') and price <= incoming.price
        and world_id <> incoming.world_id
      order by price asc, created_at asc, id asc limit 1 for update;
    else
      select * into resting from market_orders
      where galaxy = incoming.galaxy and resource = incoming.resource and side = 'buy'
        and status in ('open', 'partial') and price >= incoming.price
        and world_id <> incoming.world_id
      order by price desc, created_at asc, id asc limit 1 for update;
    end if;
    exit when not found;

    filled := least(incoming.remaining, resting.remaining);
    if filled < 1 then
      update market_orders set status = case when remaining = 0 then 'filled' else status end where id in (incoming.id, resting.id);
      exit;
    end if;

    trade_price := resting.price;

    select * into buyer from planets where world_id = case when incoming.side = 'buy' then incoming.world_id else resting.world_id end for update;
    select * into seller from planets where world_id = case when incoming.side = 'sell' then incoming.world_id else resting.world_id end for update;

    if incoming.side = 'buy' then
      -- Incoming buy gets price improvement when it crosses an older ask.
      cost := trade_price * filled;
      refunded := (incoming.price - trade_price) * filled;
      update planets
        set credits = credits + refunded,
            resources = jsonb_set(resources, array[p_resource], to_jsonb(greatest(coalesce((resources->>p_resource)::integer, 0), 0) + filled), true)
        where world_id = buyer.world_id;
      update planets set credits = credits + cost where world_id = seller.world_id;
      update market_orders
        set remaining = remaining - filled,
            escrow_credits = greatest(escrow_credits - incoming.price * filled, 0),
            status = case when remaining - filled = 0 then 'filled' else 'partial' end
        where id = incoming.id;
      update market_orders
        set remaining = remaining - filled,
            escrow_quantity = greatest(escrow_quantity - filled, 0),
            status = case when remaining - filled = 0 then 'filled' else 'partial' end
        where id = resting.id;
    else
      -- Incoming sell executes against the oldest, highest-priced resting bid.
      cost := trade_price * filled;
      update planets
        set resources = jsonb_set(resources, array[p_resource], to_jsonb(greatest(coalesce((resources->>p_resource)::integer, 0), 0) + filled), true)
        where world_id = buyer.world_id;
      update planets set credits = credits + cost where world_id = seller.world_id;
      update market_orders
        set remaining = remaining - filled,
            escrow_quantity = greatest(escrow_quantity - filled, 0),
            status = case when remaining - filled = 0 then 'filled' else 'partial' end
        where id = incoming.id;
      update market_orders
        set remaining = remaining - filled,
            escrow_credits = greatest(escrow_credits - cost, 0),
            status = case when remaining - filled = 0 then 'filled' else 'partial' end
        where id = resting.id;
    end if;

    insert into market_trades(galaxy, resource, price, quantity, buyer_world_id, seller_world_id)
    values (incoming.galaxy, p_resource, trade_price, filled,
      case when incoming.side = 'buy' then incoming.world_id else resting.world_id end,
      case when incoming.side = 'sell' then incoming.world_id else resting.world_id end);

    select * into incoming from market_orders where id = incoming.id for update;
    exit when incoming.remaining = 0;
  end loop;

  return jsonb_build_object(
    'ok', true,
    'order_id', incoming.id,
    'status', incoming.status,
    'remaining', incoming.remaining
  );
end;
$$;

create or replace function public.cancel_market_order(
  p_world_id text,
  p_owner_token text,
  p_order_id bigint
) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  o market_orders%rowtype;
  me planets%rowtype;
  available integer;
begin
  select * into me from planets where world_id = p_world_id for update;
  if not found then raise exception 'Planet not found'; end if;
  if me.owner_token <> p_owner_token then raise exception 'Not your planet'; end if;

  select * into o from market_orders where id = p_order_id for update;
  if not found or o.world_id <> p_world_id then raise exception 'Order not found'; end if;
  if o.status in ('filled', 'cancelled') then return jsonb_build_object('ok', true, 'status', o.status); end if;

  if o.side = 'buy' then
    update planets set credits = credits + o.escrow_credits, updated_at = now() where world_id = p_world_id;
  else
    available := greatest(coalesce((me.resources->>o.resource)::integer, 0), 0);
    update planets set resources = jsonb_set(resources, array[o.resource], to_jsonb(available + o.escrow_quantity), true), updated_at = now()
    where world_id = p_world_id;
  end if;

  update market_orders
    set status = 'cancelled', remaining = 0, escrow_quantity = 0, escrow_credits = 0
    where id = o.id;
  return jsonb_build_object('ok', true, 'status', 'cancelled');
end;
$$;

grant execute on function public.place_market_order(text, text, text, text, bigint, integer) to service_role;
grant execute on function public.cancel_market_order(text, text, bigint) to service_role;
revoke all on function public.place_market_order(text, text, text, text, bigint, integer) from public, anon, authenticated;
revoke all on function public.cancel_market_order(text, text, bigint) from public, anon, authenticated;
