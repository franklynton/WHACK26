create table if not exists public.market_prices (
  galaxy text not null references public.galaxies(code) on delete cascade,
  resource text not null check (resource in ('food', 'wood', 'stone', 'metal', 'gold', 'herbs')),
  base_price bigint not null check (base_price > 0),
  current_price bigint not null check (current_price > 0),
  updated_at timestamptz not null default now(),
  primary key (galaxy, resource)
);

create table if not exists public.market_price_history (
  id bigint generated by default as identity primary key,
  galaxy text not null references public.galaxies(code) on delete cascade,
  resource text not null check (resource in ('food', 'wood', 'stone', 'metal', 'gold', 'herbs')),
  price bigint not null check (price > 0),
  created_at timestamptz not null default now()
);

create index if not exists market_price_history_lookup
  on public.market_price_history (galaxy, resource, created_at desc);

alter table public.market_prices enable row level security;
alter table public.market_price_history enable row level security;

grant all privileges on table public.market_prices to service_role;
grant all privileges on table public.market_price_history to service_role;
grant usage, select on sequence public.market_price_history_id_seq to service_role;

insert into public.market_prices (galaxy, resource, base_price, current_price)
select g.code, p.resource, p.base_price, p.base_price
from public.galaxies g
cross join (values
  ('food', 8::bigint),
  ('wood', 12::bigint),
  ('stone', 15::bigint),
  ('metal', 20::bigint),
  ('gold', 30::bigint),
  ('herbs', 25::bigint)
) as p(resource, base_price)
on conflict (galaxy, resource) do nothing;

insert into public.market_price_history (galaxy, resource, price, created_at)
select galaxy, resource, base_price, now()
from public.market_prices m
where not exists (
  select 1 from public.market_price_history h
  where h.galaxy = m.galaxy and h.resource = m.resource
);

create or replace function public.record_market_price()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.market_prices (galaxy, resource, base_price, current_price)
  values (
    new.galaxy,
    new.resource,
    case new.resource
      when 'food' then 8
      when 'wood' then 12
      when 'stone' then 15
      when 'metal' then 20
      when 'gold' then 30
      else 25
    end,
    new.price
  )
  on conflict (galaxy, resource) do update set
    current_price = excluded.current_price,
    updated_at = now();

  insert into public.market_price_history (galaxy, resource, price, created_at)
  values (new.galaxy, new.resource, new.price, new.created_at);
  return new;
end;
$$;

drop trigger if exists market_trade_price_update on public.market_trades;
create trigger market_trade_price_update
after insert on public.market_trades
for each row execute function public.record_market_price();
