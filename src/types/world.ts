// The shared world-state schema. Every track reads and writes this shape, so change
// it together (and tell the team) rather than adding private copies of fields.

export type Terrain = "ocean" | "plains" | "forest" | "mountain" | "desert";

// The planet is split into 12 regions (one per vertex of an icosahedron), so the
// renderer, the simulation and the narrator can all say "region 3" and mean the same place.
export const REGION_COUNT = 12;

export interface Region {
  id: number; // 0..11
  terrain: Terrain;
  population: number; // people living here
  fertility: number; // 0-100, how much food this region can grow
}

// Needs decay over time, like Millennium Bug's pet stats. 0 = collapse, 100 = perfect.
export interface Needs {
  food: number;
  faith: number;
  stability: number;
}

// Everything the LLM has invented about this civilisation. Null until genesis.
export interface Civ {
  name: string; // what they call themselves
  demonym: string; // e.g. "the Vael"
  language: { name: string; words: Record<string, string> }; // a few invented words: english -> theirs
  religion: {
    name: string;
    godName: string; // what they call the player
    belief: string; // one sentence on what they think the player is
  };
  attitude: Attitude; // how they currently feel about the player
  myths: string[]; // newest last, at most ~8
  laws: string[]; // newest last, at most ~8
}

export type Attitude = "worship" | "fear" | "indifferent" | "resentful" | "hostile";

// Collapse states that the simulation triggers when needs fall too low.
export type Crisis = "famine" | "revolution" | "cult";

export type GodActionKind = "water" | "mountain" | "drought" | "miracle";

export interface GodAction {
  kind: GodActionKind;
  regionId: number;
}

export type ChronicleKind = GodActionKind | Crisis | "genesis" | "era" | "contact";

// One line of the running history shown to the player. Written by the narrator.
export interface ChronicleEntry {
  year: number;
  kind: ChronicleKind;
  text: string;
}

export interface World {
  id: string;
  ownerName: string;
  year: number; // in-world years since genesis; the simulation advances this
  regions: Region[];
  needs: Needs;
  crisis: Crisis | null;
  civ: Civ | null;
  chronicle: ChronicleEntry[]; // newest last
}

// ---- Multiplayer galaxy (Supabase Realtime) ----

// The part of a civ that other players' clients see, and that the contact LLM gets.
export interface CivSummary {
  name: string;
  demonym: string;
  language: Civ["language"];
  religion: Civ["religion"];
  attitude: Attitude;
  needs: Needs; // a hungry civ wants food, an unstable one wants allies, and so on
  population: number;
}

// What each planet shares with everyone in the galaxy via presence.
export interface GalaxyPlanet {
  worldId: string;
  ownerName: string;
  civ: CivSummary | null; // null until genesis
  position: { x: number; y: number }; // 0-1 on the galaxy map, derived from worldId
}

export type ContactIntent = "greet" | "trade" | "threaten" | "misunderstand" | "ally" | "war";

// How a first contact ends. Each side's world is changed by it (see applyContact in sim.ts).
export type ContactOutcome = "trade" | "alliance" | "war" | "misunderstanding";

// One turn of a negotiation between two civilisations, generated by the LLM
// speaking as one side, which only knows what the other side has said so far.
export interface ContactTurn {
  fromWorldId: string;
  toWorldId: string;
  speaker: string; // civ name
  text: string; // what they said (may include invented words)
  intent: ContactIntent;
}

// Everything broadcast on the galaxy channel. The player who starts a contact
// generates the turns one at a time and broadcasts each, so both screens (and
// any onlookers) see the same conversation as it happens.
export type GalaxyEvent =
  | { type: "contact-start"; contactId: string; a: string; b: string } // world ids; a started it
  | { type: "contact-turn"; contactId: string; turn: ContactTurn }
  | { type: "contact-end"; contactId: string; a: string; b: string; outcome: ContactOutcome; summary: string };
